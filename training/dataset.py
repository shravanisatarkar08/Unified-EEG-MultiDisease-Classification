"""
training/dataset.py - PyTorch Dataset and DataLoader pipeline for Unified EEG
Multi-Disease Classification.

Design principles
-----------------
* **Lazy loading**: raw EEG files are opened only when a sample is requested
  (__getitem__), keeping memory proportional to batch size rather than
  the full dataset size.
* **Subject-level leakage prevention**: the train / val / test split is
  determined solely by the ``split`` column in `model_dataset_index.csv`,
  which was generated by ``preprocessing.dataset_split`` with zero subject
  overlap enforced.
* **No fabricated data**: Depression (MODMA) windows are absent from the index;
  this module never synthesises EEG signals.
* **Output contract** (per sample):
    - ``eeg``      – torch.float32 tensor, shape [19, 1280]
    - ``label``    – int (Python), matches CLASS_TO_IDX
    - ``meta``     – dict with provenance keys (see EEGDataset.__getitem__)

Supported source file formats
------------------------------
* ``.edf``  – via MNE ``read_raw_edf``
* ``.set``  – via MNE ``read_raw_eeglab``

Both formats are opened with ``preload=False`` (lazy) and a single
channel-window slice is extracted on demand.

Usage
-----
    from training import get_dataloaders

    loaders = get_dataloaders(
        index_csv="datasets/metadata/model_dataset_index.csv",
        project_root=".",
        batch_size=32,
        num_workers=0,
    )
    train_loader = loaders["train"]
    for eeg, label, meta in train_loader:
        # eeg: [B, 19, 1280] float32
        # label: [B] int64
        ...
"""

from __future__ import annotations

import logging
import sys
import warnings
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import numpy as np
import pandas as pd
import torch
from torch.utils.data import DataLoader, Dataset

# ---------------------------------------------------------------------------
# Path bootstrap so module works when imported from any working directory
# ---------------------------------------------------------------------------
_MODULE_DIR = Path(__file__).resolve().parent
PROJECT_ROOT_DEFAULT = _MODULE_DIR.parent
if str(PROJECT_ROOT_DEFAULT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT_DEFAULT))

# Suppress MNE noise
warnings.filterwarnings("ignore", category=RuntimeWarning, module="mne")
warnings.filterwarnings("ignore", category=UserWarning, module="mne")

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Canonical label mapping (mirrors preprocessing.dataset_split)
# ---------------------------------------------------------------------------

CLASS_TO_IDX: Dict[str, int] = {
    "healthy": 0,
    "epilepsy": 1,
    "alzheimers": 2,
    "parkinsons": 3,
    "depression": 4,
}

IDX_TO_CLASS: Dict[int, str] = {v: k for k, v in CLASS_TO_IDX.items()}

# ---------------------------------------------------------------------------
# Target channel layouts (mirrors preprocessing.harmonization)
# ---------------------------------------------------------------------------

TARGET_19_MONOPOLAR: List[str] = [
    "Fp1", "Fp2", "F7", "F3", "Fz", "F4", "F8",
    "T3", "C3", "Cz", "C4", "T4",
    "T5", "P3", "Pz", "P4", "T6",
    "O1", "O2",
]

TARGET_19_BIPOLAR: List[str] = [
    "FP1-F7", "F7-T7", "T7-P7", "P7-O1",
    "FP1-F3", "F3-C3", "C3-P3", "P3-O1",
    "FP2-F4", "F4-C4", "C4-P4", "P4-O2",
    "FP2-F8", "F8-T8", "T8-P8", "P8-O2",
    "FZ-CZ", "CZ-PZ",
    "P7-T7",
]

# 10-10 → 10-20 aliases (for monopolar lookup)
_CH_ALIASES: Dict[str, str] = {
    "T7": "T3", "T8": "T4", "P7": "T5", "P8": "T6",
    "FP1": "Fp1", "FP2": "Fp2", "FZ": "Fz", "CZ": "Cz", "PZ": "Pz",
}

# Target shape constants
N_CHANNELS = 19
N_SAMPLES = 1280  # 5 s × 256 Hz


# ---------------------------------------------------------------------------
# Low-level: channel extraction from MNE raw (no full-file preload)
# ---------------------------------------------------------------------------

def _build_monopolar_map(ch_names: List[str]) -> Dict[str, int]:
    """Return upper-case channel name → raw channel index mapping with alias expansion."""
    src_map: Dict[str, int] = {}
    for i, ch in enumerate(ch_names):
        clean = ch.strip()
        src_map[clean.upper()] = i
        if clean in _CH_ALIASES:
            alias_std = _CH_ALIASES[clean]
            if alias_std.upper() not in src_map:
                src_map[alias_std.upper()] = i
    return src_map


def _build_bipolar_map(ch_names: List[str]) -> Dict[str, int]:
    """Return simplified bipolar channel name (upper-case, no trailing digit) → index."""
    import re
    src_map: Dict[str, int] = {}
    for i, ch in enumerate(ch_names):
        clean = re.sub(r"-(\d+)$", "", ch).upper()
        src_map[clean] = i
    return src_map


def _extract_window_from_raw(
    raw,
    start_sample: int,
    n_samples: int,
    is_bipolar: bool,
) -> np.ndarray:
    """
    Slice [19, n_samples] from an already-open MNE Raw object.

    Parameters
    ----------
    raw : mne.io.Raw (preload=False is fine; MNE will read the slice on demand)
    start_sample : int  first sample index (in the raw file's native srate)
    n_samples : int     number of samples to read (in raw native srate)
    is_bipolar : bool   True for CHB-MIT bipolar montage

    Returns
    -------
    np.ndarray  shape [19, n_samples], dtype float32
                Missing channels are zero-filled.
    """
    n_raw_samples = raw.n_times
    end_sample = start_sample + n_samples

    # Guard: clamp to valid range
    if start_sample >= n_raw_samples or start_sample < 0:
        return np.zeros((N_CHANNELS, n_samples), dtype=np.float32)

    end_sample = min(end_sample, n_raw_samples)
    actual_len = end_sample - start_sample

    # Read only the required slice  (MNE uses inclusive tmax in seconds)
    t_start = start_sample / raw.info["sfreq"]
    t_stop = end_sample / raw.info["sfreq"]
    # get_data returns [n_ch, n_samp]
    raw_slice, _ = raw[:, start_sample:end_sample]  # shape [n_raw_ch, actual_len]

    output = np.zeros((N_CHANNELS, n_samples), dtype=np.float32)

    if is_bipolar:
        import re
        target_channels = TARGET_19_BIPOLAR
        src_map = _build_bipolar_map(raw.ch_names)
        for idx, tch in enumerate(target_channels):
            tch_clean = re.sub(r"-(\d+)$", "", tch).upper()
            if tch_clean in src_map:
                output[idx, :actual_len] = raw_slice[src_map[tch_clean], :actual_len]
    else:
        target_channels = TARGET_19_MONOPOLAR
        src_map = _build_monopolar_map(raw.ch_names)
        for idx, tch in enumerate(target_channels):
            if tch.upper() in src_map:
                output[idx, :actual_len] = raw_slice[src_map[tch.upper()], :actual_len]

    return output


# ---------------------------------------------------------------------------
# EEG file cache (process-local; avoids reopening the same file for every
# window when windows from the same recording are batched consecutively)
# ---------------------------------------------------------------------------

class _RawFileCache:
    """Very simple LRU-like cache: keep last `maxsize` open MNE Raw objects."""

    def __init__(self, maxsize: int = 4) -> None:
        self._maxsize = maxsize
        self._cache: Dict[str, object] = {}  # path → mne.io.Raw
        self._order: List[str] = []

    def get(self, path: str, is_edf: bool):
        if path not in self._cache:
            raw = self._open(path, is_edf)
            if len(self._order) >= self._maxsize:
                evict = self._order.pop(0)
                try:
                    self._cache[evict].close()
                except Exception:
                    pass
                del self._cache[evict]
            self._cache[path] = raw
            self._order.append(path)
        else:
            # Move to end (most recently used)
            self._order.remove(path)
            self._order.append(path)
        return self._cache[path]

    @staticmethod
    def _open(path: str, is_edf: bool):
        import mne
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            if is_edf:
                raw = mne.io.read_raw_edf(path, preload=False, verbose=False)
            else:
                raw = mne.io.read_raw_eeglab(path, preload=False, verbose=False)
        return raw

    def close_all(self) -> None:
        for raw in self._cache.values():
            try:
                raw.close()
            except Exception:
                pass
        self._cache.clear()
        self._order.clear()


# Module-level cache; each DataLoader worker process gets its own copy after
# fork(), so there is no cross-process sharing issue.
_file_cache = _RawFileCache(maxsize=8)


# ---------------------------------------------------------------------------
# PyTorch Dataset
# ---------------------------------------------------------------------------

class EEGDataset(Dataset):
    """
    Lazy-loading PyTorch Dataset backed by ``model_dataset_index.csv``.

    Each call to ``__getitem__`` opens the corresponding EEG file on disk
    (or re-uses a cached MNE Raw handle), slices the requested 5-second
    window, harmonises channels to 19, and returns a float32 tensor of
    shape [19, 1280].

    Parameters
    ----------
    index_df : pd.DataFrame
        Rows from ``model_dataset_index.csv`` for a single split.
    project_root : Path | str
        Absolute path to the project root; used to resolve relative
        ``source_file`` paths in the index.
    cache_size : int
        Number of MNE Raw file handles to keep open simultaneously.

    Outputs per item
    ----------------
    eeg   : torch.Tensor  shape [19, 1280], dtype float32
    label : int           integer class label (CLASS_TO_IDX value)
    meta  : dict          provenance keys:
                            dataset_name, subject_id, class_category,
                            source_file, window_idx, window_start_sec,
                            window_end_sec, is_bipolar_montage,
                            missing_channels, split
    """

    def __init__(
        self,
        index_df: pd.DataFrame,
        project_root: Path | str = PROJECT_ROOT_DEFAULT,
        cache_size: int = 8,
    ) -> None:
        self.index_df = index_df.reset_index(drop=True)
        self.project_root = Path(project_root)
        self._cache = _RawFileCache(maxsize=cache_size)

    # ------------------------------------------------------------------
    def __len__(self) -> int:
        return len(self.index_df)

    # ------------------------------------------------------------------
    def __getitem__(self, idx: int) -> Tuple[torch.Tensor, int, dict]:
        row = self.index_df.iloc[idx]

        # ---- Resolve file path ----------------------------------------
        src_file = str(row["source_file"])
        # Index stores paths relative to project root  (e.g. datasets/raw/…)
        file_path = self.project_root / src_file
        if not file_path.exists():
            # Fallback: treat as absolute
            file_path = Path(src_file)

        abs_path = str(file_path)
        is_edf = abs_path.lower().endswith(".edf")

        # ---- Compute sample indices from window metadata ---------------
        sampling_rate = float(row.get("sampling_rate", 256.0))
        window_start_sec = float(row["window_start_sec"])
        start_sample = int(round(window_start_sec * sampling_rate))

        # ---- Determine montage type -----------------------------------
        is_bipolar_str = str(row.get("is_bipolar_montage", "False")).strip()
        is_bipolar = is_bipolar_str.lower() in ("true", "1", "yes")

        # ---- Lazy file access ----------------------------------------
        try:
            raw = self._cache.get(abs_path, is_edf=is_edf)

            # Native sampling rate may differ from target 256 Hz
            native_srate = raw.info["sfreq"]
            # Recompute start_sample in native srate
            native_start = int(round(window_start_sec * native_srate))
            native_window = int(round(5.0 * native_srate))  # 5-second window

            raw_window = _extract_window_from_raw(
                raw, native_start, native_window, is_bipolar
            )

            # ---- Resample to 256 Hz if native srate differs ----------
            if abs(native_srate - 256.0) > 1.0:
                import scipy.signal
                orig = int(round(native_srate))
                tgt = 256
                from math import gcd
                g = gcd(orig, tgt)
                up, down = tgt // g, orig // g
                resampled = scipy.signal.resample_poly(raw_window, up, down, axis=1)
                # Ensure exactly N_SAMPLES=1280 samples
                if resampled.shape[1] >= N_SAMPLES:
                    raw_window = resampled[:, :N_SAMPLES].astype(np.float32)
                else:
                    pad_len = N_SAMPLES - resampled.shape[1]
                    raw_window = np.pad(
                        resampled, ((0, 0), (0, pad_len)), mode="constant"
                    ).astype(np.float32)
            else:
                # Already at 256 Hz: ensure exact length
                if raw_window.shape[1] > N_SAMPLES:
                    raw_window = raw_window[:, :N_SAMPLES]
                elif raw_window.shape[1] < N_SAMPLES:
                    pad_len = N_SAMPLES - raw_window.shape[1]
                    raw_window = np.pad(
                        raw_window, ((0, 0), (0, pad_len)), mode="constant"
                    ).astype(np.float32)

        except Exception as exc:
            logger.warning(
                f"[EEGDataset] Failed to load '{abs_path}' "
                f"(window {row['window_idx']}): {exc}. Returning zeros."
            )
            raw_window = np.zeros((N_CHANNELS, N_SAMPLES), dtype=np.float32)

        # ---- Tensor conversion ----------------------------------------
        eeg_tensor = torch.from_numpy(raw_window)  # [19, 1280], float32

        # ---- Label ----------------------------------------------------
        class_label_idx = int(row["class_label_idx"])

        # ---- Provenance metadata dict ---------------------------------
        missing_raw = row.get("missing_channels", "")
        missing_channels = (
            [c for c in str(missing_raw).split("|") if c]
            if pd.notna(missing_raw) and str(missing_raw).strip()
            else []
        )

        meta = {
            "dataset_name": str(row["dataset_name"]),
            "subject_id": str(row["subject_id"]),
            "class_category": str(row["class_category"]),
            "source_file": src_file,
            "window_idx": int(row["window_idx"]),
            "window_start_sec": float(row["window_start_sec"]),
            "window_end_sec": float(row["window_end_sec"]),
            "is_bipolar_montage": is_bipolar,
            "missing_channels": missing_channels,
            "split": str(row["split"]),
        }

        return eeg_tensor, class_label_idx, meta



def get_dataloaders(
    index_csv: str | Path = "datasets/metadata/model_dataset_index.csv",
    project_root: str | Path = PROJECT_ROOT_DEFAULT,
    batch_size: int = 32,
    num_workers: int = 0,
    pin_memory: bool = False,
    cache_size: int = 8,
    shuffle_train: bool = True,
) -> Dict[str, DataLoader]:
    """
    Build train / val / test DataLoaders from ``model_dataset_index.csv``.

    Subject-level leakage prevention is **inherited from the index file**,
    which was generated by ``preprocessing.dataset_split.SubjectLevelSplitter``
    with ``verify_zero_leakage`` enforced.

    Parameters
    ----------
    index_csv : str | Path
        Path to ``model_dataset_index.csv`` (absolute or relative to cwd).
    project_root : str | Path
        Project root used to resolve relative ``source_file`` paths.
    batch_size : int
        Samples per mini-batch.
    num_workers : int
        Parallel data-loading workers (0 = main process only).
    pin_memory : bool
        Pin tensors in CUDA pinned memory (speeds up GPU transfer).
    cache_size : int
        Number of Raw file handles to keep open per worker.
    shuffle_train : bool
        Shuffle the training split each epoch.

    Returns
    -------
    dict with keys ``"train"``, ``"val"``, ``"test"`` (only present if the
    corresponding split has rows in the index).
    """
    index_csv = Path(index_csv)
    if not index_csv.is_absolute():
        # Try relative to cwd first, then relative to project_root
        cwd_path = Path.cwd() / index_csv
        root_path = Path(project_root) / index_csv
        if cwd_path.exists():
            index_csv = cwd_path
        elif root_path.exists():
            index_csv = root_path

    if not index_csv.exists():
        raise FileNotFoundError(
            f"[get_dataloaders] model_dataset_index.csv not found at: {index_csv}"
        )

    df = pd.read_csv(index_csv)
    logger.info(
        f"[get_dataloaders] Loaded index: {len(df)} rows from {index_csv}"
    )

    # Verify no Depression (MODMA) rows – policy check
    depression_rows = df[df["class_category"] == "depression"]
    if len(depression_rows) > 0:
        raise ValueError(
            f"[get_dataloaders] Found {len(depression_rows)} depression (MODMA) rows "
            "in the index. MODMA is unavailable locally; no fabricated data allowed."
        )

    loaders: Dict[str, DataLoader] = {}

    split_configs = {
        "train": {"shuffle": shuffle_train, "drop_last": False},
        "val": {"shuffle": False, "drop_last": False},
        "test": {"shuffle": False, "drop_last": False},
    }

    for split_name, kwargs in split_configs.items():
        split_df = df[df["split"] == split_name].copy()
        if split_df.empty:
            logger.info(f"[get_dataloaders] No rows for split='{split_name}'; skipping.")
            continue

        dataset = EEGDataset(
            index_df=split_df,
            project_root=project_root,
            cache_size=cache_size,
        )

        loader = DataLoader(
            dataset,
            batch_size=batch_size,
            shuffle=kwargs["shuffle"],
            num_workers=num_workers,
            pin_memory=pin_memory,
            drop_last=kwargs["drop_last"],
            # collate_fn: default works because meta dict is not batched by
            # default PyTorch collate — we handle that below.
            collate_fn=_eeg_collate_fn,
        )
        loaders[split_name] = loader
        logger.info(
            f"[get_dataloaders] split='{split_name}': {len(dataset)} windows, "
            f"{len(loader)} batches of size {batch_size}"
        )

    return loaders


# ---------------------------------------------------------------------------
# Custom collate: stack tensors + labels, collect meta as list-of-dicts
# ---------------------------------------------------------------------------

def _eeg_collate_fn(batch):
    """
    Collate a list of (eeg_tensor, label, meta_dict) into:
        eeg_batch : torch.Tensor  [B, 19, 1280] float32
        labels    : torch.Tensor  [B] int64
        metas     : list of dict  length B
    """
    eeg_list, label_list, meta_list = zip(*batch)
    eeg_batch = torch.stack(eeg_list, dim=0)          # [B, 19, 1280]
    labels = torch.tensor(label_list, dtype=torch.long)  # [B]
    return eeg_batch, labels, list(meta_list)
